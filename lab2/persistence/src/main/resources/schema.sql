CREATE TABLE IF NOT EXISTS books (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
 title VARCHAR(255) NOT NULL, author VARCHAR(255) NOT NULL, pub_year INT NOT NULL CHECK(pub_year BETWEEN 1 AND 9999)
);
CREATE TABLE IF NOT EXISTS comments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 book_id BIGINT NOT NULL REFERENCES books(id), author VARCHAR(64) NOT NULL,
 text VARCHAR(1000) NOT NULL, created_at TIMESTAMP(9) WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_comments_book_created ON comments(book_id, created_at);
