package app.db;

import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

public final class CommentDao {
    public void init() throws SQLException {
        try (var connection = Db.get(); var statement = connection.createStatement()) {
            statement.execute("""
                    create table if not exists comments (
                        id bigint generated by default as identity primary key,
                        author varchar(64) not null,
                        text varchar(1000) not null,
                        created_at timestamp not null default current_timestamp
                    )
                    """);
        }
    }

    public long add(String author, String text) throws SQLException {
        try (var connection = Db.get();
             var statement = connection.prepareStatement(
                     "insert into comments(author, text) values (?, ?)", Statement.RETURN_GENERATED_KEYS)) {
            statement.setString(1, author);
            statement.setString(2, text);
            statement.executeUpdate();
            try (var keys = statement.getGeneratedKeys()) {
                if (!keys.next()) {
                    throw new SQLException("The database did not return a generated comment ID");
                }
                return keys.getLong(1);
            }
        }
    }

    public List<Map<String, Object>> list() throws SQLException {
        try (var connection = Db.get();
             var statement = connection.prepareStatement(
                     "select id, author, text, created_at from comments order by id desc");
             var rows = statement.executeQuery()) {
            var comments = new ArrayList<Map<String, Object>>();
            while (rows.next()) {
                var comment = new LinkedHashMap<String, Object>();
                comment.put("id", rows.getLong("id"));
                comment.put("author", rows.getString("author"));
                comment.put("text", rows.getString("text"));
                comment.put("createdAt", rows.getTimestamp("created_at").toInstant().toString());
                comments.add(comment);
            }
            return comments;
        }
    }
}
